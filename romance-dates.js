function finishCoupleDate(id,data,choice){
 state.coupleNotes??={};
 const notes=state.coupleNotes[id]??={};
 if(!data.specialDate)state.dateOrder[id].shift();
 const action=choice[4];
 notes.recalled=action==='remark'||action==='repair'?action:null;
 notes.visit=action==='visit';
 if(action==='hurt')notes.hurt=true;
 if(action==='pause')notes.paused=true;
 if(action==='repair'){notes.hurt=false;notes.paused=false;}
}
